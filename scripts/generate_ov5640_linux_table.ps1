param(
    [string]$SourcePath,
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $SourcePath) {
    $SourcePath = Join-Path $repoRoot `
        'SDK\ov5640_hdmi_frame_difference\src\ov5640\ov5640_init.c'
}
if (-not $OutputPath) {
    $OutputPath = Join-Path $repoRoot `
        'linux\ov5640_init\ov5640-init-table.h'
}

$valueSources = @{
    'cmos_h_pixel>>8'       = 'OV5640_VALUE_WIDTH_HI'
    'cmos_h_pixel&0x00ff'   = 'OV5640_VALUE_WIDTH_LO'
    'cmos_v_pixel>>8'       = 'OV5640_VALUE_HEIGHT_HI'
    'cmos_v_pixel&0x00ff'   = 'OV5640_VALUE_HEIGHT_LO'
    'total_h_pixel>>8'      = 'OV5640_VALUE_HTOTAL_HI'
    'total_h_pixel&0x00ff'  = 'OV5640_VALUE_HTOTAL_LO'
    'total_v_pixel>>8'      = 'OV5640_VALUE_VTOTAL_HI'
    'total_v_pixel&0x00ff'  = 'OV5640_VALUE_VTOTAL_LO'
}

$sourceLines = Get-Content -LiteralPath $SourcePath
$entries = [System.Collections.Generic.List[string]]::new()

for ($index = 0; $index -lt $sourceLines.Count; ++$index) {
    $line = $sourceLines[$index]

    # The anchor deliberately excludes the commented-out 48 MHz PLL write.
    if ($line -notmatch '^\s*sccb_write_reg16\s*\(\s*(0x[0-9A-Fa-f]+)\s*,\s*([^\)]+)\)\s*;') {
        continue
    }

    $register = $Matches[1].ToLowerInvariant()
    $expression = ($Matches[2] -replace '\s', '').ToLowerInvariant()

    if ($expression -match '^0x[0-9a-f]+$') {
        $value = $expression
    } elseif ($valueSources.ContainsKey($expression)) {
        $value = $valueSources[$expression]
    } else {
        throw "Unsupported value expression at source line $($index + 1): $expression"
    }

    # Preserve the proven bare-metal delay after the software-reset write.
    $delayUs = if ($register -eq '0x3008' -and $value -eq '0x82') {
        10000
    } else {
        0
    }

    $entries.Add(('    {{ {0}, {1}, {2} }}, /* source line {3} */' -f `
            $register, $value, $delayUs, ($index + 1)))
}

if ($entries.Count -eq 0) {
    throw "No active sccb_write_reg16 calls found in $SourcePath"
}

$header = [System.Collections.Generic.List[string]]::new()
$header.Add('/* Auto-generated by scripts/generate_ov5640_linux_table.ps1. */')
$header.Add('/* Source: SDK/ov5640_hdmi_frame_difference/src/ov5640/ov5640_init.c */')
$header.Add('/* Do not hand-edit this file; update the proven source or generator. */')
$header.Add('#ifndef OV5640_INIT_TABLE_H')
$header.Add('#define OV5640_INIT_TABLE_H')
$header.Add('')
$header.Add('#include <stdint.h>')
$header.Add('')
$header.Add('enum ov5640_value_source {')
$header.Add('    OV5640_VALUE_WIDTH_HI = 0x100,')
$header.Add('    OV5640_VALUE_WIDTH_LO,')
$header.Add('    OV5640_VALUE_HEIGHT_HI,')
$header.Add('    OV5640_VALUE_HEIGHT_LO,')
$header.Add('    OV5640_VALUE_HTOTAL_HI,')
$header.Add('    OV5640_VALUE_HTOTAL_LO,')
$header.Add('    OV5640_VALUE_VTOTAL_HI,')
$header.Add('    OV5640_VALUE_VTOTAL_LO,')
$header.Add('};')
$header.Add('')
$header.Add('struct ov5640_register_write {')
$header.Add('    uint16_t reg;')
$header.Add('    uint16_t value_or_source;')
$header.Add('    uint32_t delay_after_us;')
$header.Add('};')
$header.Add('')
$header.Add('static const struct ov5640_register_write ov5640_init_sequence[] = {')
$header.AddRange($entries)
$header.Add('};')
$header.Add('')
$header.Add('#define OV5640_INIT_SEQUENCE_COUNT \')
$header.Add('    (sizeof(ov5640_init_sequence) / sizeof(ov5640_init_sequence[0]))')
$header.Add('')
$header.Add('#endif')

$outputDirectory = Split-Path -Parent $OutputPath
if (-not (Test-Path -LiteralPath $outputDirectory)) {
    New-Item -ItemType Directory -Path $outputDirectory | Out-Null
}

[System.IO.File]::WriteAllLines(
    $OutputPath,
    $header,
    [System.Text.UTF8Encoding]::new($false)
)

Write-Host "Generated $($entries.Count) register writes: $OutputPath"
